// Compute polygon area (shoelace) for each country -> used for territory percentage
function polygonArea(poly) {
  let a = 0;
  for (let i = 0; i < poly.length; i++) {
    const [x1,y1] = poly[i];
    const [x2,y2] = poly[(i+1) % poly.length];
    a += x1*y2 - x2*y1;
  }
  return Math.abs(a) / 2;
}

